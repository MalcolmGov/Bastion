const test = require('node:test');
const assert = require('node:assert/strict');
const { createHarness } = require('./harness.cjs');
async function setup(t) {
  const h = await createHarness(); t.after(() => h.close());
  const store = h.load('lib/results/store.ts');
  const document = { issuer: 'Synthetic', periodLabel: '2026', unit: 'R000', narrative: ['Original report'], highlights: [], statements: [], notes: [], warnings: [], sourceFilename: 'test.pdf', pageCount: 1, sourcePages: [{ page: 1, dataUrl: 'source-evidence' }], presentationHtml: '<html><body>Original report<img src="data:image/png;base64,aGVsbG8=" /></body></html>' };
  const saved = await store.saveResultsDocument({ clientId: 'tenant-a', document, status: 'draft', actor: { id: 'author-a', name: 'Author' } });
  const route = h.route('api/admin/results/[id]/history');
  const context = { params: Promise.resolve({ id: saved.id }) };
  const get = async (query = '') => route.GET(h.request('/api/admin/results/' + saved.id + '/history' + query, {}, null, 'GET'), context);
  const post = async (action, version, current = saved, extra = {}) => route.POST(h.request('/api/admin/results/' + saved.id + '/history', { action, revisionId: version, expectedUpdatedAt: current.updatedAt, sourceReviewed: true, validationReviewed: true, comment: 'Compared with PDF', ...extra }), context);
  h.user({ id: 'author-a', name: 'Author', role: 'content_editor', client_id: 'tenant-a' });
  return { h, store, saved, document, get, post };
}
test('history enforces tenant, roles, independent approval and saved revision identity', async t => {
  const { h, get, post, saved } = await setup(t);
  const history = await (await get()).json(); const revision = history.currentRevisionId;
  assert.equal(history.versions.length, 1);
  const inspected = await (await get('?revision=' + revision)).json();
  assert.deepEqual(inspected.changes, ['Same report content']);
  assert.ok(!JSON.stringify(history).includes('Original report'));
  assert.ok(!JSON.stringify(history).includes('aGVsbG8'));
  assert.equal((await post('approve', revision)).status, 403);
  h.user({ role: 'platform_admin', client_id: null });
  assert.equal((await post('approve', revision)).status, 409, 'even an admin cannot approve own version');
  h.user({ id: 'reviewer-a', name: 'Reviewer', role: 'reviewer', client_id: 'tenant-b' });
  assert.equal((await get()).status, 404);
  assert.equal((await post('approve', revision)).status, 404);
  h.user({ client_id: 'tenant-a' });
  assert.equal((await post('approve', revision, saved, { sourceReviewed: false })).status, 409);
  assert.equal((await post('approve', 'invented')).status, 409);
  assert.equal((await post('approve', revision, { ...saved, updatedAt: 'stale' })).status, 409);
  assert.equal((await post('approve', revision)).status, 200);
  assert.equal((await (await get()).json()).versions[0].reviewer_name, 'Reviewer');
  assert.equal((await get('?revision=another-document-version')).status, 404);
});
test('approved snapshots stay live through editing and restore; each changed version needs approval', async t => {
  const { h, store, saved, document, get, post } = await setup(t);
  const v1 = (await (await get()).json()).currentRevisionId;
  await assert.rejects(() => store.saveResultsDocument({ id: saved.id, document, status: 'published' }), /approval/);
  h.user({ id: 'reviewer-a', name: 'Reviewer', role: 'reviewer', client_id: 'tenant-a' });
  assert.equal((await post('approve', v1)).status, 200);
  const published = await store.saveResultsDocument({ id: saved.id, document, status: 'published', expectedUpdatedAt: saved.updatedAt });
  const unchanged = await store.saveResultsDocument({ id: saved.id, document, status: 'draft', expectedUpdatedAt: published.updatedAt });
  assert.equal((await (await get()).json()).versions.length, 1, 'unchanged saves reuse the approved revision');
  const changed = { ...document, narrative: ['Edited draft'], presentationHtml: document.presentationHtml.replace('Original report', 'Edited draft') };
  const draft = await store.saveResultsDocument({ id: saved.id, document: changed, status: 'draft', expectedUpdatedAt: unchanged.updatedAt, actor: { id: 'author-a', name: 'Author' } });
  assert.notEqual(draft.updatedAt, unchanged.updatedAt);
  assert.equal((await store.getPublishedResultsBySlug(saved.slug)).document.narrative[0], 'Original report');
  await assert.rejects(() => store.saveResultsDocument({ id: saved.id, document: changed, status: 'published', expectedUpdatedAt: draft.updatedAt }), /approval/);
  h.user({ id: 'author-a', name: 'Author', role: 'content_editor', client_id: 'tenant-a' });
  const restoredResponse = await post('restore', v1, draft);
  assert.equal(restoredResponse.status, 200); const restored = await restoredResponse.json();
  assert.equal(restored.status, 'draft'); assert.equal(restored.document.sourcePages[0].dataUrl, 'source-evidence');
  assert.equal(restored.document.narrative[0], 'Original report');
  const history = await (await get()).json(); assert.equal(history.versions.length, 3);
  assert.equal(history.versions[0].restored_from, v1); assert.equal(history.versions[0].reviewed_at, null);
  assert.equal((await store.getPublishedResultsBySlug(saved.slug)).document.narrative[0], 'Original report');
  assert.equal((await h.db.execute('SELECT COUNT(*) AS total FROM results_revision_assets')).rows[0].total, 1, 'artwork is deduplicated');
  const count = history.versions.length;
  await assert.rejects(() => store.saveResultsDocument({ id: saved.id, document: changed, status: 'draft', expectedUpdatedAt: draft.updatedAt }), /another session/);
  assert.equal((await (await get()).json()).versions.length, count, 'stale writes cannot append history');
});
test('legacy published report gets an honest baseline and remains online after first draft save', async t => {
  const { h, store, saved, document, get } = await setup(t);
  await h.db.execute({ sql: 'DELETE FROM results_revisions WHERE document_id = ?', args: [saved.id] });
  await h.db.execute({ sql: "UPDATE results_documents SET status = 'published', published_at = updated_at WHERE id = ?", args: [saved.id] });
  assert.equal((await (await get()).json()).versions.length, 0);
  await store.saveResultsDocument({ id: saved.id, document: { ...document, narrative: ['New draft'] }, status: 'draft', expectedUpdatedAt: saved.updatedAt, actor: { id: 'author-a', name: 'Author' } });
  assert.equal((await store.getPublishedResultsBySlug(saved.slug)).document.narrative[0], 'Original report');
  const history = await (await get()).json();
  assert.equal(history.versions[1].author_id, null); assert.equal(history.versions[1].author_name, 'Legacy baseline');
  assert.ok(history.versions[1].published_at);
});
test('review requests and paginated history contain metadata only', async t => {
  const { h, store, saved, document, get, post } = await setup(t);
  const revision = (await (await get()).json()).currentRevisionId;
  assert.equal((await post('request', revision)).status, 200);
  assert.equal((await (await get()).json()).versions[0].requested_name, 'Author');
  for (let index = 0; index < 51; index++) await store.saveResultsDocument({ id: saved.id, document: { ...document, title: 'Revision ' + index }, status: 'draft', actor: { id: 'author-a', name: 'Author' } });
  const first = await (await get()).json(); const last = await (await get('?offset=50')).json();
  assert.equal(first.versions.length, 50); assert.equal(first.nextOffset, 50); assert.equal(last.versions.length, 2); assert.equal(last.nextOffset, null);
  assert.ok(!JSON.stringify(first).includes('snapshot_json')); assert.ok(!JSON.stringify(first).includes('data:image'));
  assert.equal((await get('?offset=-1')).status, 400);
});
